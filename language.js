const applyLanguage = language => {
    const dictionary = translations[language];
    if (!dictionary) throw new Error(`Unsupported language: ${language}`);

    document.documentElement.lang = language;

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const translation = dictionary[element.dataset.i18n];
        if (translation !== undefined) element.textContent = translation;
    });
    document.querySelectorAll('[data-i18n-content]').forEach(element => {
        const translation = dictionary[element.dataset.i18nContent];
        if (translation !== undefined) element.setAttribute('content', translation);
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(element => {
        const translation = dictionary[element.dataset.i18nAlt];
        if (translation !== undefined) element.setAttribute('alt', translation);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
        const translation = dictionary[element.dataset.i18nAriaLabel];
        if (translation !== undefined) element.setAttribute('aria-label', translation);
    });
    document.querySelectorAll('[data-language-label]').forEach(element => {
        element.textContent = language === 'th' ? 'EN' : 'ไทย';
    });
    document.querySelectorAll('.nav-toggle').forEach(element => {
        const key = element.getAttribute('aria-expanded') === 'true' ? 'nav-close' : 'nav-open';
        element.setAttribute('aria-label', dictionary[key]);
    });
    document.querySelectorAll('meta[property="og:locale"]').forEach(element => {
        element.setAttribute('content', language === 'th' ? 'th_TH' : 'en_US');
    });

    window.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
};

let currentLanguage = 'en';
try {
    const savedLanguage = window.localStorage.getItem('mnsw-language');
    if (savedLanguage && Object.prototype.hasOwnProperty.call(translations, savedLanguage)) {
        currentLanguage = savedLanguage;
    }
} catch (error) {
    console.warn('Unable to load the saved language preference.', error);
}

applyLanguage(currentLanguage);

document.querySelectorAll('.language-toggle').forEach(button => {
    button.addEventListener('click', () => {
        currentLanguage = currentLanguage === 'th' ? 'en' : 'th';
        applyLanguage(currentLanguage);
        try {
            window.localStorage.setItem('mnsw-language', currentLanguage);
        } catch (error) {
            console.warn('Unable to save the language preference.', error);
        }
    });
});
